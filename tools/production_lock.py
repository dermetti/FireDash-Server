"""Resolve and hash binary production wheels for CPython 3.13 / Debian 13 amd64.

Requires the development environment's packaging library. No application imports.
Cross-target pip still evaluates some markers on the host: validate and select the
complete Linux dependency closure explicitly, failing on missing/conflicting edges.
"""

import argparse
import hashlib
import json
import re

# Fixed pip argument vector; no shell.
import subprocess  # nosec B404
import sys
import tempfile
import urllib.request
from pathlib import Path
from urllib.parse import unquote, urlparse

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name, parse_wheel_filename
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements/production.lock"
CONSTRAINTS = ROOT / "requirements/production-constraints.txt"
INPUT = ROOT / "requirements/base.txt"
TARGET: dict[str, str] = {
    "os_name": "posix",
    "sys_platform": "linux",
    "platform_system": "Linux",
    "platform_machine": "x86_64",
    "platform_release": "",
    "platform_version": "",
    "python_version": "3.13",
    "python_full_version": "3.13.0",
    "implementation_name": "cpython",
    "implementation_version": "3.13.0",
    "platform_python_implementation": "CPython",
}


def direct_requirements():
    return [
        Requirement(line)
        for line in INPUT.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]


def dependency_closure(items, roots):
    selected = {}
    inspected = set()
    pending = list(roots)
    while pending:
        requirement = pending.pop()
        name = canonicalize_name(requirement.name)
        if name not in items:
            raise ValueError(f"Missing target dependency: {name}")
        item = items[name]
        metadata = item["metadata"]
        if Version(metadata["version"]) not in requirement.specifier:
            raise ValueError(f"Conflicting target dependency: {name}")
        selected[name] = item
        for extra in {"", *requirement.extras}:
            if (name, extra) in inspected:
                continue
            inspected.add((name, extra))
            for entry in metadata.get("requires_dist", []):
                dependency = Requirement(entry)
                if dependency.marker is None or dependency.marker.evaluate(
                    {**TARGET, "extra": extra}
                ):
                    pending.append(dependency)
    return selected


def generate(constraints: Path):
    with tempfile.TemporaryDirectory() as scratch:
        report = Path(scratch) / "resolution.json"
        # Fixed resolver command and local reviewed requirement inputs.
        subprocess.run(  # nosec B603
            [
                sys.executable,
                "-m",
                "pip",
                "--isolated",
                "--disable-pip-version-check",
                "install",
                "--dry-run",
                "--ignore-installed",
                "--no-cache-dir",
                "--index-url",
                "https://pypi.org/simple",
                "--keyring-provider",
                "disabled",
                "--only-binary=:all:",
                "--platform",
                "manylinux_2_28_x86_64",
                "--platform",
                "manylinux_2_17_x86_64",
                "--python-version",
                "3.13",
                "--implementation",
                "cp",
                "--abi",
                "cp313",
                "--report",
                str(report),
                "-r",
                str(INPUT),
                "-c",
                str(constraints),
            ],
            check=True,
            timeout=600,
        )
        items = {
            canonicalize_name(item["metadata"]["name"]): item
            for item in json.loads(report.read_text(encoding="utf-8"))["install"]
        }
    selected = dependency_closure(items, direct_requirements())
    lines = [
        "# Generated by python tools/production_lock.py generate; do not edit.",
        "# Target: Debian 13 amd64, CPython 3.13; binary wheels only.",
        "# SHA-256 checked against PyPI metadata AND downloaded wheel bytes.",
    ]
    pins = []
    for name, item in sorted(selected.items()):
        version = item["metadata"]["version"]
        download = item["download_info"]
        url = download["url"]
        parsed = urlparse(url)
        if parsed.scheme != "https" or parsed.hostname != "files.pythonhosted.org":
            raise ValueError("Unexpected distribution origin")
        filename = unquote(parsed.path.rsplit("/", 1)[1])
        wheel_name, wheel_version, _, tags = parse_wheel_filename(filename)
        if wheel_name != name or str(wheel_version) != version:
            raise ValueError("Unexpected distribution identity")
        if not any(
            (tag.platform == "any" and tag.interpreter in ("py2", "py3"))
            or (
                tag.platform in ("manylinux_2_17_x86_64", "manylinux_2_28_x86_64")
                and (tag.interpreter == "cp313" or tag.abi == "abi3")
            )
            for tag in tags
        ):
            raise ValueError("Unsupported wheel target")
        # Fixed HTTPS PyPI origin.
        with urllib.request.urlopen(  # nosec B310
            f"https://pypi.org/pypi/{name}/{version}/json", timeout=60
        ) as response:
            metadata = json.load(response)
        expected = download["archive_info"]["hashes"]["sha256"]
        distribution = next(entry for entry in metadata["urls"] if entry["filename"] == filename)
        if distribution["digests"]["sha256"] != expected or distribution["yanked"]:
            raise ValueError("Untrusted or yanked distribution")
        digest = hashlib.sha256()
        # HTTPS distribution origin was checked above.
        with urllib.request.urlopen(url, timeout=60) as response:  # nosec B310
            while chunk := response.read(1024 * 1024):
                digest.update(chunk)
        if digest.hexdigest() != expected:
            raise ValueError("Distribution hash mismatch")
        # Keep the binary extra so pip also enforces psycopg-binary's dependency.
        pin = f"{name}{'[binary]' if name == 'psycopg' else ''}=={version}"
        pins.append(f"{name}=={version}")
        lines.extend([f"# {filename}", f"{pin} --hash=sha256:{expected}"])
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    CONSTRAINTS.write_text(
        "# Generated alongside production.lock; versions only for development tooling.\n"
        + "\n".join(pins)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    check()


def check():
    entries = {}
    for line in LOCK.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        match = re.fullmatch(
            r"([a-z0-9-]+(?:\[binary\])?)==([^ ]+) --hash=sha256:([0-9a-f]{64})", line
        )
        if not match:
            raise ValueError("Invalid lock entry")
        requirement = Requirement(f"{match[1]}=={match[2]}")
        name = canonicalize_name(requirement.name)
        if name in entries:
            raise ValueError("Duplicate lock entry")
        entries[name] = match[2]
    constraints = {}
    for line in CONSTRAINTS.read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            requirement = Requirement(line)
            constraints[canonicalize_name(requirement.name)] = str(requirement.specifier)[2:]
    if not entries or constraints != entries:
        raise ValueError("Production constraints differ from lock")
    for requirement in direct_requirements():
        name = canonicalize_name(requirement.name)
        if name not in entries or Version(entries[name]) not in requirement.specifier:
            raise ValueError(f"Direct input differs from lock: {name}")
    print(f"Production lock consistent: {len(entries)} pinned packages")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("generate", "check"))
    parser.add_argument("--constraints", type=Path, default=CONSTRAINTS)
    options = parser.parse_args()
    if options.action == "generate":
        generate(options.constraints)
    else:
        check()
